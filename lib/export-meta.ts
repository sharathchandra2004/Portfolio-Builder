import type { Profile } from "@/lib/profile";

export function exportReadme(profile: Profile): string {
  const slug = (profile.name || "portfolio").toLowerCase().replace(/[^a-z0-9]+/g, "-");
  return `# ${profile.name || "Portfolio"} — exported site

This folder is a standalone static portfolio generated by **folio**. It does not require an API key or account.

## Local preview

1. Open \`index.html\` in your browser, or serve the folder:

\`\`\`bash
npx serve .
\`\`\`

## Deploy to Vercel

1. Push this folder to a Git repository (or use the Vercel CLI).
2. Import the project at [vercel.com/new](https://vercel.com/new).
3. Framework preset: **Other** (static). Output directory: \`.\`
4. Deploy.

## Deploy to Netlify

1. Drag this folder into [Netlify Drop](https://app.netlify.com/drop), or connect a Git repo.
2. Build command: *(leave empty)* — Publish directory: \`.\`
3. Deploy.

## Customize

- Edit \`index.html\` directly, or re-import your profile in folio and export again.
- Replace project images by updating \`<img src="...">\` URLs.

Generated design: **${profile.design}** (${profile.category}).
Site slug suggestion: \`${slug}\`.
`;
}

export function exportPackageJson(): string {
  return JSON.stringify(
    {
      name: "portfolio-site",
      private: true,
      version: "1.0.0",
      scripts: { start: "npx serve ." },
    },
    null,
    2,
  );
}
